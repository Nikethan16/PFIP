# Printable PDF summary
# ---------------------------------------------------------------------------


def build_summary_pdf(
    summary: TaxSummary,
    events: list[CGEvent] | None = None,
    fa_rows: list[ScheduleFARow] | None = None,
    f67_rows: list[Form67Row] | None = None,
) -> bytes:
    """Return a single-page A4 PDF summary suitable for CA handoff.

    Falls back to a plain-text bytes buffer if reportlab is unavailable.
    """
    if not _HAS_REPORTLAB:
        lines = [
            f"PFIP TAX SUMMARY — FY {summary.fy}",
            "",
            f"Disclaimer: {DISCLAIMER}",
            "",
            f"Equity STCG: Rs. {_d(summary.stcg_equity_inr)}",
            f"Equity LTCG (pre-exempt): Rs. {_d(summary.ltcg_equity_inr)}",
            f"VDA gains: Rs. {_d(summary.vda_gain_inr)} | TDS credit: Rs. {_d(summary.vda_tds_inr)}",
            f"Dividend: Rs. {_d(summary.dividend_inr)}",
            f"Total tax (advisory): Rs. {_d(summary.total_tax_inr)}",
            f"Recommended regime: {summary.recommended_regime.upper()}",
            f"Recommended ITR: {summary.recommended_itr}",
        ]
        return ("\n".join(lines)).encode("utf-8")

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, title=f"PFIP Tax Summary FY {summary.fy}")
    styles = getSampleStyleSheet()
    story: list = []
    story.append(Paragraph(f"<b>PFIP Tax Summary — FY {summary.fy}</b>", styles["Title"]))
    story.append(Spacer(1, 8))
    story.append(Paragraph(f"<i>{DISCLAIMER}</i>", styles["Italic"]))
    story.append(Spacer(1, 12))

    head_data = [
        ["Metric", "Amount (INR)"],
        ["Equity STCG (gains)", _d(summary.stcg_equity_inr)],
        ["Equity LTCG (gains, pre-exempt)", _d(summary.ltcg_equity_inr)],
        ["VDA gains (taxable)", _d(summary.vda_gain_inr)],
        ["VDA TDS credit", _d(summary.vda_tds_inr)],
        ["Dividend (gross)", _d(summary.dividend_inr)],
        ["Interest (gross)", _d(summary.interest_inr)],
        ["Total estimated tax", _d(summary.total_tax_inr)],
        ["Recommended regime", summary.recommended_regime.upper()],
        ["Recommended ITR", summary.recommended_itr],
    ]
    t = Table(head_data, hAlign="LEFT", colWidths=[220, 160])
    t.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),
                ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ]
        )
    )
    story.append(t)

    if summary.surcharge_cliff_warnings:
        story.append(Spacer(1, 12))
        story.append(Paragraph("<b>Surcharge-cliff warnings</b>", styles["Heading3"]))
        for w in summary.surcharge_cliff_warnings:
            story.append(Paragraph("• " + w, styles["BodyText"]))

    if events:
        story.append(Spacer(1, 12))
        story.append(Paragraph("<b>Capital-gains events (first 20)</b>", styles["Heading3"]))
        rows = [["Symbol", "Term", "Sell", "Qty", "Cost", "Proceeds", "Gain"]]
        for e in events[:20]:
            rows.append(
                [
                    e.symbol,
                    e.term.value,
                    e.sell_date.isoformat(),
                    str(e.qty),
                    _d(e.buy_cost_inr),
                    _d(e.sell_proceeds_inr),
                    _d(e.gain_inr),
                ]
            )
        story.append(
            Table(
                rows,
                hAlign="LEFT",
                style=TableStyle(
                    [
                        ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
                        ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),
                        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                        ("FONTSIZE", (0, 0), (-1, -1), 8),
                    ]
                ),
            )
        )
    if fa_rows:
        story.append(Spacer(1, 12))
        story.append(Paragraph("<b>Schedule FA</b>", styles["Heading3"]))
        rows = [["Symbol", "Peak USD", "Peak INR", "Closing USD", "Dividends USD"]]
        for r in fa_rows:
            rows.append(
                [
                    r.symbol,
                    _d(r.peak_balance_usd),
                    _d(r.peak_balance_inr),
                    _d(r.closing_balance_usd),
                    _d(r.gross_dividend_usd),
                ]
            )
        story.append(Table(rows, hAlign="LEFT"))
    if f67_rows:
        story.append(Spacer(1, 12))
        story.append(Paragraph("<b>Form 67 (DTAA credit)</b>", styles["Heading3"]))
        rows = [["Source", "Foreign income INR", "Tax abroad INR", "Credit INR"]]
        for r in f67_rows:
            rows.append(
                [
                    r.source_name,
                    _d(r.foreign_income_inr),
                    _d(r.tax_paid_abroad_inr),
                    _d(r.dtaa_credit_inr),
                ]
            )
        story.append(Table(rows, hAlign="LEFT"))

    doc.build(story)
    return buf.getvalue()
