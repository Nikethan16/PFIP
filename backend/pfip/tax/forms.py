"""ITR helpers — printable PDF for CA handoff + JSON exports.

The JSON structures mirror (closely — not bit-exact) the schemas used by
Income-Tax-India's JSON upload utility for Schedule CG and Schedule FA. Any
final filing MUST be regenerated by the CA against the current Finance-Act
schema; this module is advisory.
"""

from __future__ import annotations

import io
from dataclasses import asdict
from decimal import Decimal
from typing import Any

try:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.platypus import (
        Paragraph,
        SimpleDocTemplate,
        Spacer,
        Table,
        TableStyle,
    )

    _HAS_REPORTLAB = True
except Exception:  # pragma: no cover
    _HAS_REPORTLAB = False

from pfip.tax.engine import (
    CGEvent,
    Form67Row,
    GainTerm,
    ScheduleFARow,
    TaxSummary,
)
from pfip.tax.indian_rules import DISCLAIMER


def _d(v: Any) -> str:
    """Decimal-to-string with 2 dp for human display."""
    if v is None:
        return "0.00"
    try:
        return f"{Decimal(str(v)):,.2f}"
    except Exception:
        return str(v)


def schedule_cg_json(events: list[CGEvent]) -> dict:
    """ITR-2/ITR-3 Schedule CG JSON-like structure.

    Split out STCG / LTCG and per-asset-class totals.
    """
    stcg_eq = [
        e
        for e in events
        if e.term == GainTerm.STCG and e.asset_class.value in ("equity", "equity_mf")
    ]
    ltcg_eq = [
        e
        for e in events
        if e.term == GainTerm.LTCG and e.asset_class.value in ("equity", "equity_mf")
    ]
    vda = [e for e in events if e.asset_class.value == "vda"]
    debt = [e for e in events if e.asset_class.value in ("debt", "debt_mf")]

    def _row(e: CGEvent) -> dict:
        return {
            "symbol": e.symbol,
            "asset_class": e.asset_class.value,
            "qty": str(e.qty),
            "buy_date": e.buy_date.isoformat(),
            "sell_date": e.sell_date.isoformat(),
            "cost_basis_inr": str(e.buy_cost_inr),
            "proceeds_inr": str(e.sell_proceeds_inr),
            "gain_inr": str(e.gain_inr),
            "grandfathered": e.grandfathered,
            "tds_inr": str(e.tds_inr),
        }

    total_stcg = sum((e.gain_inr for e in stcg_eq), Decimal("0"))
    total_ltcg = sum((e.gain_inr for e in ltcg_eq), Decimal("0"))
    total_vda = sum((e.gain_inr for e in vda), Decimal("0"))
    total_debt = sum((e.gain_inr for e in debt), Decimal("0"))

    return {
        "schedule": "CG",
        "equity_stcg": {
            "section": "111A",
            "items": [_row(e) for e in stcg_eq],
            "total_gain_inr": str(total_stcg),
        },
        "equity_ltcg": {
            "section": "112A",
            "items": [_row(e) for e in ltcg_eq],
            "total_gain_inr": str(total_ltcg),
        },
        "vda": {
            "section": "115BBH",
            "items": [_row(e) for e in vda],
            "total_gain_inr": str(total_vda),
            "loss_setoff_allowed": False,
        },
        "debt": {
            "items": [_row(e) for e in debt],
            "total_gain_inr": str(total_debt),
        },
        "disclaimer": DISCLAIMER,
    }


def schedule_fa_json(rows: list[ScheduleFARow]) -> dict:
    """Schedule FA JSON-like structure."""
    return {
        "schedule": "FA",
        "rows": [
            {
                "country": r.country,
                "symbol": r.symbol,
                "isin": r.isin,
                "acquired_on": r.acquired_on.isoformat() if r.acquired_on else None,
                "peak_balance_usd": str(r.peak_balance_usd),
                "peak_balance_inr": str(r.peak_balance_inr),
                "closing_balance_usd": str(r.closing_balance_usd),
                "closing_balance_inr": str(r.closing_balance_inr),
                "gross_interest_usd": str(r.gross_interest_usd),
                "gross_dividend_usd": str(r.gross_dividend_usd),
                "gross_proceeds_usd": str(r.gross_proceeds_usd),
            }
            for r in rows
        ],
        "disclaimer": DISCLAIMER,
    }


def form_67_json(rows: list[Form67Row]) -> dict:
    """Form 67 JSON-like structure."""
    total_credit = sum((r.dtaa_credit_inr for r in rows), Decimal("0"))
    return {
        "form": "67",
        "rows": [
            asdict(r) | {k: str(v) for k, v in asdict(r).items() if isinstance(v, Decimal)}
            for r in rows
        ],
        "total_dtaa_credit_inr": str(total_credit),
        "disclaimer": DISCLAIMER,
    }


